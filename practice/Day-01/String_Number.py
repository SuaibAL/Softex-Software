text = "  Softex Software  "
print(text.strip())  # Removes leading and trailing whitespace
print(text.upper())  # Converts to uppercase
print(text.lower())  # Converts to lowercase
print(text.replace("Softex", "SoftTech"))  # Replaces "Softex" with "SoftTech"
print(text.split())  # Splits the string into a list of words
print(text.startswith("Softex"))  # Checks if the string starts with "Softex"
print(text.endswith("Software"))  # Checks if the string ends with "Software"
print(text.find("Software"))  # Finds the index of "Software"
print(text.count("o"))  # Counts occurrences of "o"
print(text.isalpha())  # Checks if all characters are alphabetic
print(text.isdigit())  # Checks if all characters are digits